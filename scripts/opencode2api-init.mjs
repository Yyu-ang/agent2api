#!/usr/bin/env node
/**
 * Idempotent, dependency-free bootstrap for the optional OpenCode2API sidecar.
 *
 * No upstream Go source is copied into Agent2API. The independent upstream
 * image retains its own GPL-3.0-or-later license.
 *
 * Supply optional upstream credentials via environment variables (not CLI
 * flags, which would leak into the process list):
 *   OPENCODE2API_ZEN_KEYS=sk-...
 *   OPENCODE2API_GO_KEYS=sk-...
 *   OPENCODE2API_ANONYMOUS=1
 */
import { randomBytes } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const configPath = join(root, 'data', 'opencode2api', 'config.json')
const envPath = join(root, '.env.opencode2api')
const secret = () => randomBytes(32).toString('hex')
const keys = (value) => (value || '').split(/[\n,]+/).map((key) => key.trim()).filter(Boolean)
const zenKeys = keys(process.env.OPENCODE2API_ZEN_KEYS)
const goKeys = keys(process.env.OPENCODE2API_GO_KEYS)
const anonymous = process.env.OPENCODE2API_ANONYMOUS === '1'
  || (!zenKeys.length && !goKeys.length && process.env.OPENCODE2API_ANONYMOUS !== '0')

let config
if (existsSync(configPath)) {
  config = JSON.parse(readFileSync(configPath, 'utf8'))
  console.log('Existing OpenCode2API seed config retained; no upstream keys/passwords overwritten.')
} else {
  mkdirSync(dirname(configPath), { recursive: true })
  config = {
    listen: '0.0.0.0:8080',
    server_keys: [`a2a-${secret()}`],
    zen_keys: zenKeys,
    go_keys: goKeys,
    anonymous,
    proxies: ['direct'],
    upstream: { zen: 'https://opencode.ai/zen', go: 'https://opencode.ai/zen/go' },
    retry: { max_attempts: 3, timeout_seconds: 300 },
    models: { refresh_seconds: 300, protocols: {} },
    webui: {
      enabled: true,
      listen: '0.0.0.0:8081',
      username: 'admin',
      password: secret(),
      session_ttl_minutes: 720,
    },
    prefer: 'go',
    reasoning: { effort: 'high', effort_by_model: {} },
    rotation: {
      sota: { alias: 'sota', order: ['deepseek-v4.1-flash', 'glm-5.3', 'grok-4.6', 'kimi-k3', 'qwen3.8-max'] },
      sweet: { alias: 'sweet', order: [] },
      first_output_seconds: 30,
    },
  }
  writeFileSync(configPath, JSON.stringify(config, null, 2) + '\n', { encoding: 'utf8', mode: 0o600, flag: 'wx' })
  console.log('Created private upstream seed config (Zen/Go credentials, if supplied, stored locally).')
}

const apiKey = config?.server_keys?.[0]
if (typeof apiKey !== 'string' || !apiKey.trim()) {
  throw new Error('Existing upstream config has no usable server_keys[0]; refusing to generate a broken bridge.')
}
// Compose interpolation needs only its local gateway key. Zen and Go account
// keys are NEVER written into the environment file or the Agent2API database.
const envContent = `# Generated by scripts/opencode2api-init.mjs. Do not commit.\nOPENCODE2API_SERVER_KEY=${apiKey}\n`
if (existsSync(envPath)) {
  const current = readFileSync(envPath, 'utf8')
  const match = current.match(/^OPENCODE2API_SERVER_KEY=(.*)$/m)
  if (!match || match[1].trim() !== apiKey.trim()) {
    throw new Error('Existing .env.opencode2api does not match server_keys[0]. Refusing to rotate credentials silently.')
  }
} else {
  writeFileSync(envPath, envContent, { encoding: 'utf8', mode: 0o600, flag: 'wx' })
}
console.log('Private sidecar connection configuration is ready.')
console.log('Start with:')
console.log('  docker compose --env-file .env.opencode2api -f docker-compose.yml -f docker-compose.opencode2api.yml up -d --build')
console.log('Models and account will be registered automatically in Agent2API at first gateway start.')
console.log('Management UI (localhost only): http://127.0.0.1:18081')
